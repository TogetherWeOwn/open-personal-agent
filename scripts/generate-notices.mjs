// Generates THIRD_PARTY_NOTICES.md for the production dependencies in the lockfile (ADR 0011 #1),
// with each package's licence and NOTICE text. Fails on a missing or disallowed licence.
import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { isMain, readText, report } from "./lib/repo.mjs";

/** Licences we cannot ship in an Apache-2.0 product bundle (ADR 0011 #2). */
const DISALLOWED = /\b(?:A?GPL|LGPL|SSPL|BUSL|UNLICENSED|Unknown)\b/i;
const LEGAL_FILE = /^(?:LICEN[CS]E|COPYING|NOTICE)(?:[.-].*)?$/i;

/** `pnpm licenses list --json` output → [{ id: "name@version", license, path }], sorted. */
export const flatten = (licensesJson) =>
  Object.values(licensesJson)
    .flat()
    .flatMap(({ name, versions, paths, license }) =>
      versions.map((v, i) => ({
        id: `${name}@${v}`,
        license: license ?? "Unknown",
        path: paths?.[i],
      })),
    )
    .sort((a, b) => a.id.localeCompare(b.id));

export function disallowed(packages) {
  return packages
    .filter((p) => DISALLOWED.test(p.license))
    .map((p) => `${p.id}: licence "${p.license}" is not allowed`);
}

function render(packages) {
  const parts = ["# Third-party notices", "", "Generated by `pnpm notices`. Do not edit by hand."];
  for (const { id, license, path } of packages) {
    parts.push("", `## ${id}`, "", `Licence: ${license}`);
    for (const file of path
      ? readdirSync(path)
          .filter((f) => LEGAL_FILE.test(f))
          .sort()
      : []) {
      parts.push("", `### ${file}`, "", "```text", readText(join(path, file))?.trimEnd(), "```");
    }
  }
  return `${parts.join("\n")}\n`;
}

if (isMain(import.meta.url)) {
  const out = process.argv[2] ?? "dist/THIRD_PARTY_NOTICES.md";
  const json = execFileSync("pnpm", ["licenses", "list", "--prod", "--json"], { encoding: "utf8" });
  const packages = flatten(JSON.parse(json));
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, render(packages));
  console.log(`wrote ${out} (${packages.length} packages)`);
  report("notices", disallowed(packages));
}
